namespace VuFind\Action\QRCode;

use Psr\Http\Message\ResponseInterface;
use Psr\Http\Message\ServerRequestInterface;

/**
 * Show QRCode action.
 *
 * @category VuFind
 * @package  Action
 * @author   Demian Katz <demian.katz@villanova.edu>
 * @author   Luke O'Sullivan <l.osullivan@swansea.ac.uk>
 * @author   Ere Maijala <ere.maijala@helsinki.fi>
 * @license  http://opensource.org/licenses/gpl-2.0.php GNU General Public License
 * @link     https://vufind.org Main Site
 */
class ShowAction extends AbstractQRCodeAction
{
    /**
     * Show a QRCode.
     *
     * @param ServerRequestInterface $request  Server request
     * @param ResponseInterface      $response Response
     *
     * @return ResponseInterface
     */
    public function action(
        ServerRequestInterface $request,
        ResponseInterface $response,
    ): ResponseInterface {
        $this->sessionSettings->disableWrite(); // avoid session write timing bug

        $params = [];
        foreach ($this->qrCodeLoader->getDefaults() as $param => $default) {
            $params[$param] = $this->getQueryParam($param, $default);
        }
        $this->qrCodeLoader->loadQRCode($this->getQueryParam('text', ''), $params);
        return $this->displayQRCode($response);
    }
}
